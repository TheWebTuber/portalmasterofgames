export function classFeatureNames(
  className: string,
  subclass: string,
  level: number,
): string[] {
  if (!Object.hasOwn(classes, className) || !Number.isFinite(level)) return [];
  const progression = classes[className];
  const specialization = subclasses[className];
  const selected: Progression =
    specialization.name === subclass ? specialization.features : {};
  const features: string[] = [];
  for (let rank = 1; rank <= Math.min(20, level); rank++) {
    for (const name of [
      ...(progression[rank] ?? []),
      ...(selected[rank] ?? []),
    ]) {
      features.push(`Level ${rank} · ${name}`);
    }
  }
  return features;
}
